#!/usr/bin/env python3
"""Generate js/era-events.js from ../era_events.csv (single source of truth).

Run from the repo root:  python3 tools/gen-era-events.py
The CSV is the WorkBuddy-filled chronicle table (1977-2026, 69 rows), with
machine columns `cond` + `fx` added 2026-11-17 (tools/add-era-cond-fx.py):
cond = structured exposure condition (see era.js eventApplies),
fx = numeric effects (money range in 万 -> family cash; other keys are
fixed deltas on the player's attrs; offerMod sets flags.gradOfferMod).
Only status == '已核实' rows are ever applied (see era.js); 待核实 rows
are kept in the module for display/debug but never routed.
Re-run after any CSV update and commit both files together.
"""
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
CSV_PATH = os.path.join(REPO, '..', 'era_events.csv')
OUT_PATH = os.path.join(REPO, 'js', 'era-events.js')


def main():
    with open(CSV_PATH, encoding='utf-8') as f:
        rows = list(csv.DictReader(f))
    events = []
    counts = {'已核实': 0, '待核实': 0}
    for r in rows:
        events.append({
            'year': int(r['year']),
            'event': r['event'],
            'ageMin': int(r['age_min']),
            'ageMax': int(r['age_max']),
            'tier': r['tier'],
            'condition': r['condition'] or '',
            'note': r['note'] or '',
            'status': r['status'],
            'cond': json.loads(r['cond'] or '{}'),
            'fx': json.loads(r['fx'] or '{}'),
        })
        counts[r['status']] = counts.get(r['status'], 0) + 1
    meta = {
        'generatedFrom': 'era_events.csv (WorkBuddy fill 2026-11-17, cond+fx 2026-11-17)',
        'rows': len(rows),
        'verified': counts.get('已核实', 0),
        'toVerify': counts.get('待核实', 0),
    }
    with open(OUT_PATH, 'w', encoding='utf-8') as f:
        f.write('// GENERATED by tools/gen-era-events.py from era_events.csv — do not hand-edit.\n')
        f.write('// 69 rows, 1977-2026; 67 已核实, 2 待核实 (2025/2026, never applied).\n')
        f.write('const ERA_EVENTS = ')
        f.write(json.dumps(events, ensure_ascii=False, separators=(',', ':')))
        f.write(';\nconst ERA_EVENTS_META = ')
        f.write(json.dumps(meta, ensure_ascii=False, separators=(',', ':')))
        f.write(';\n')
        f.write("if (typeof module !== 'undefined') { module.exports = { ERA_EVENTS, ERA_EVENTS_META }; }\n")
    print(f'wrote {OUT_PATH}: {len(rows)} rows, {meta}')


if __name__ == '__main__':
    sys.exit(main())
