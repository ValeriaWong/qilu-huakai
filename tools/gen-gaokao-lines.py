#!/usr/bin/env python3
"""Generate js/gaokao-lines.js from ../gaokao_lines.csv (single source of truth).

Run from the repo root:  python3 tools/gen-gaokao-lines.py
The CSV is the WorkBuddy-filled table (2010-2020 verified, 2026 to_verify,
the rest unprovided). The generated module keeps every row with its status;
only status == '已核实' rows with an undergrad line are playable (see era.js).
Re-run after any CSV update (e.g. the 2021/2022 fill or a resolved 2026
conflict) and commit both files together.
"""
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
CSV_PATH = os.path.join(REPO, '..', 'gaokao_lines.csv')
OUT_PATH = os.path.join(REPO, 'js', 'gaokao-lines.js')


def num(s):
    s = (s or '').strip()
    return int(s) if s else None


def main():
    with open(CSV_PATH, encoding='utf-8') as f:
        rows = list(csv.DictReader(f))
    lines = {}
    counts = {'已核实': 0, '待核实': 0, '未提供': 0}
    for r in rows:
        key = '|'.join([r['province'], r['year'], r['track']])
        lines[key] = {
            'tier1': num(r['tier1']),
            'tier2': num(r['tier2']),
            'tier3': num(r['tier3']),
            'vocational': num(r['vocational']),
            'regime': r['regime'] or None,
            'note': r['note'] or '',
            'status': r['status'],
        }
        counts[r['status']] = counts.get(r['status'], 0) + 1
    meta = {
        'generatedFrom': 'gaokao_lines.csv (WorkBuddy fill 2026-11-17)',
        'rows': len(rows),
        'verified': counts.get('已核实', 0),
        'toVerify': counts.get('待核实', 0),
        'unprovided': counts.get('未提供', 0),
    }
    with open(OUT_PATH, 'w', encoding='utf-8') as f:
        f.write('// GENERATED by tools/gen-gaokao-lines.py from gaokao_lines.csv — do not hand-edit.\n')
        f.write(f"// {meta['verified']} verified; {meta['toVerify']} to_verify; {meta['unprovided']} unprovided; {meta['rows']} rows total.\n")
        f.write('const GAOKAO_LINES = ')
        f.write(json.dumps(lines, ensure_ascii=False, separators=(',', ':')))
        f.write(';\nconst GAOKAO_LINES_META = ')
        f.write(json.dumps(meta, ensure_ascii=False, separators=(',', ':')))
        f.write(';\n')
        f.write("if (typeof module !== 'undefined') { module.exports = { GAOKAO_LINES, GAOKAO_LINES_META }; }\n")
    print(f'wrote {OUT_PATH}: {len(rows)} rows, {meta}')


if __name__ == '__main__':
    sys.exit(main())
